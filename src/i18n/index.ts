export type TranslationKey = keyof (typeof translations)['pt-BR'];

export function translate(
  locale: Locale,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  const dict = translations[locale] ?? translations.en;
  let template: string = dict[key] ?? translations.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      template = template.replaceAll(`{${k}}`, String(v));
    }
  }
  return template;
}

/** Base keys that have `_one`/`_other` plural variants. */
export type PluralKey = {
  [K in TranslationKey]: K extends `${infer Base}_other` ? Base : never;
}[TranslationKey];

/** Picks the `_one`/`_other` variant with `Intl.PluralRules` and fills `{count}`. */
export function translatePlural(
  locale: Locale,
  key: PluralKey,
  count: number,
  vars?: Record<string, string | number>
): string {
  const category = new Intl.PluralRules(locale).select(count);
  const variant = (category === 'one' ? `${key}_one` : `${key}_other`) as TranslationKey;
  return translate(locale, variant, { count, ...vars });
}
